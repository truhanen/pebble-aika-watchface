GFont WidgetFonts_get(uint8_t index) {
  static GFont s_cache[WIDGET_FONT_COUNT];
  if (index >= WIDGET_FONT_COUNT) { index = WIDGET_FONT_DEFAULT_SIDE; }
  if (!s_cache[index]) { s_cache[index] = fonts_get_system_font(FONT_KEYS[index]); }
  return s_cache[index];
}
